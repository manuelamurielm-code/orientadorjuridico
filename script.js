document.addEventListener('DOMContentLoaded', () => {
    
    // --- 1. Theme Toggle (Light/Dark Mode) ---
    const themeBtn = document.getElementById('theme-toggle');
    const htmlElement = document.documentElement;
    const sunIcon = document.querySelector('.sun-icon');
    const moonIcon = document.querySelector('.moon-icon');

    const savedTheme = localStorage.getItem('theme');
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    
    if (savedTheme === 'dark' || (!savedTheme && prefersDark)) {
        htmlElement.setAttribute('data-theme', 'dark');
        sunIcon.style.display = 'none';
        moonIcon.style.display = 'block';
    }

    themeBtn.addEventListener('click', () => {
        const currentTheme = htmlElement.getAttribute('data-theme');
        const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
        
        htmlElement.setAttribute('data-theme', newTheme);
        localStorage.setItem('theme', newTheme);
        
        if (newTheme === 'dark') {
            sunIcon.style.display = 'none';
            moonIcon.style.display = 'block';
        } else {
            sunIcon.style.display = 'block';
            moonIcon.style.display = 'none';
        }
    });

    // --- 2. Tab Switching Logic ---
    const tabBtns = document.querySelectorAll('.tab-btn');
    const tabPanes = document.querySelectorAll('.tab-pane');

    tabBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            tabBtns.forEach(b => b.classList.remove('active'));
            tabPanes.forEach(p => p.classList.remove('active'));
            
            btn.classList.add('active');
            const tabId = btn.getAttribute('data-tab');
            document.getElementById(tabId).classList.add('active');
        });
    });

    // --- 3. Language Selector Logic ---
    const langSelect = document.getElementById('lang-select');
    
    const setLanguage = (lang) => {
        if (!translations[lang]) return;
        
        document.documentElement.lang = lang;
        
        // Update regular i18n text
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });

        // Update placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (translations[lang][key]) {
                el.setAttribute('placeholder', translations[lang][key]);
            }
        });

        localStorage.setItem('lang', lang);
        langSelect.value = lang;
    };

    langSelect.addEventListener('change', (e) => {
        setLanguage(e.target.value);
    });

    // Initialize Language
    const savedLang = localStorage.getItem('lang') || 'es';
    setLanguage(savedLang);


    // --- 4. Scroll Animations ---
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    const animateElements = document.querySelectorAll('.intro-step, .info-card, .glossary-item, .chat-interface, .disclaimer, .glass-container, .author-card');
    
    animateElements.forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(20px)';
        el.style.transition = 'all 0.5s ease-out';
        observer.observe(el);
    });

    // --- 5. Interactive Chat (Mock) ---
    const chatHistory = document.getElementById('chat-history');
    const userInput = document.getElementById('user-input');
    const sendBtn = document.getElementById('send-btn');

    const appendUserMessage = (text) => {
        const msgDiv = document.createElement('div');
        msgDiv.className = 'demo-input';
        msgDiv.innerHTML = `
            <div class="avatar user">U</div>
            <div class="message">${text}</div>
        `;
        chatHistory.appendChild(msgDiv);
        chatHistory.scrollTop = chatHistory.scrollHeight;
    };

    const appendLoading = () => {
        const loadingDiv = document.createElement('div');
        loadingDiv.className = 'demo-output loading-msg';
        loadingDiv.innerHTML = `
            <div class="avatar bot">OJ</div>
            <div class="message">
                <div class="loading-dots">
                    <span></span><span></span><span></span>
                </div>
            </div>
        `;
        chatHistory.appendChild(loadingDiv);
        chatHistory.scrollTop = chatHistory.scrollHeight;
        return loadingDiv;
    };

    const appendBotMessage = (text) => {
        const msgDiv = document.createElement('div');
        msgDiv.className = 'demo-output';
        msgDiv.innerHTML = `
            <div class="avatar bot">OJ</div>
            <div class="message">${text}</div>
        `;
        chatHistory.appendChild(msgDiv);
        chatHistory.scrollTop = chatHistory.scrollHeight;
    };

    const getMockResponse = (text, lang) => {
        if (lang === 'en') {
            return `
                <strong>1. Legal Translation:</strong> Possible violation of rights based on the exposed facts.<br><br>
                <strong>2. Rights Involved:</strong> Right to due process, right of petition and related fundamental rights.<br><br>
                <strong>3. Applicable Regulations:</strong> Political Constitution of Colombia, relevant Codes.<br><br>
                <strong>4. Action Mechanisms:</strong> 
                <ul>
                    <li>Attempt out-of-court conciliation.</li>
                    <li>Submit a Right of Petition.</li>
                    <li>Consider a Tutela Action if there is an imminent risk.</li>
                </ul>
                <strong>5. Competent Authorities:</strong> Houses of Justice, Legal Clinics, Judges.<br><br>
                <hr style="opacity: 0.2; margin: 15px 0;">
                <em>*Note: This response was generated as an interactive educational example.</em>
            `;
        } else if (lang === 'pt') {
            return `
                <strong>1. Tradução Jurídica:</strong> Possível violação de direitos com base nos fatos expostos.<br><br>
                <strong>2. Direitos Envolvidos:</strong> Direito ao devido processo, direito de petição e direitos fundamentais relacionados.<br><br>
                <strong>3. Regulamentos Aplicáveis:</strong> Constituição Política da Colômbia, Códigos relevantes.<br><br>
                <strong>4. Mecanismos de Ação:</strong> 
                <ul>
                    <li>Tentar conciliação extrajudicial.</li>
                    <li>Apresentar um Direito de Petição.</li>
                    <li>Considerar uma Ação de Tutela se houver risco iminente.</li>
                </ul>
                <strong>5. Autoridades Competentes:</strong> Casas de Justiça, Clínicas Jurídicas, Juízes.<br><br>
                <hr style="opacity: 0.2; margin: 15px 0;">
                <em>*Nota: Esta resposta foi gerada como um exemplo educacional interativo.</em>
            `;
        }
        
        // Default (ES)
        return `
            <strong>1. Traducción Jurídica:</strong> Posible vulneración de derechos en base a los hechos expuestos.<br><br>
            <strong>2. Derechos Involucrados:</strong> Derecho al debido proceso, derecho de petición y derechos fundamentales conexos.<br><br>
            <strong>3. Normativa Aplicable:</strong> Constitución Política de Colombia, Códigos pertinentes.<br><br>
            <strong>4. Mecanismos de Acción:</strong> 
            <ul>
                <li>Intentar conciliación extrajudicial.</li>
                <li>Presentar un Derecho de Petición.</li>
                <li>Considerar una Acción de Tutela si existe riesgo inminente.</li>
            </ul>
            <strong>5. Autoridades Competentes:</strong> Casas de Justicia, Consultorios Jurídicos, Jueces o Defensoría del Pueblo.<br><br>
            <hr style="opacity: 0.2; margin: 15px 0;">
            <em>*Nota: Esta respuesta fue generada como un ejemplo pedagógico interactivo de nuestra landing page.</em>
        `;
    };

    const handleSend = () => {
        const text = userInput.value.trim();
        if (!text) return;

        appendUserMessage(text);
        userInput.value = '';

        const loadingDiv = appendLoading();

        setTimeout(() => {
            chatHistory.removeChild(loadingDiv);
            const currentLang = localStorage.getItem('lang') || 'es';
            appendBotMessage(getMockResponse(text, currentLang));
        }, 2000);
    };

    sendBtn.addEventListener('click', handleSend);
    userInput.addEventListener('keypress', (e) => {
        if (e.key === 'Enter' && !e.shiftKey) {
            e.preventDefault();
            handleSend();
        }
    });

});
